                ?: System.getenv("GOOGLE_MAPS_API_KEY")
                ?: ""
        manifestPlaceholders["GOOGLE_MAPS_API_KEY"] = mapsKey
    }

    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
